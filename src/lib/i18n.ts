const normalize = (text: string) => text.replace(/\s+/g, " ").trim().toLocaleLowerCase();
const dictionaries: Record<Lang, Map<string, string>> = {
  English: new Map(),
  "Bahasa Melayu": new Map(),
};
for (const [english, malay] of translations) {
  for (const source of [english, malay]) {
    dictionaries.English.set(normalize(source), english);
    dictionaries["Bahasa Melayu"].set(normalize(source), malay);
  }
}
const escapeRegex = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// Single longest-first pass, with word boundaries: never compound replacements
// or translate inside a name, email, report identifier or another translated word.
const fragments = [...dictionaries.English.keys()].sort((a, b) => b.length - a.length);
const phrasePattern = new RegExp(
  `(?<![\\p{L}\\p{N}_@])(?:${fragments.map(escapeRegex).join("|")})(?![\\p{L}\\p{N}_@])`,
  "giu",
);

export function translate(text: string, language: Lang): string {
  if (!text.trim()) return text;
  const dictionary = dictionaries[language];
  const direct = dictionary.get(normalize(text));
  if (direct !== undefined) return text.replace(text.trim(), direct);
  return text.replace(phrasePattern, (part) => dictionary.get(normalize(part)) ?? part);
}

/** Localize primitive display values, never props, objects, IDs or stored values. */
export function localizeNode<T extends ReactNode>(node: T, t: (text: string) => string): T {
  if (typeof node === "string") return t(node) as T;
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, t)) as unknown as T;
  return node;
}
